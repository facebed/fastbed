fb_crawler_db *fb_crawler_db_load_embedded(char *error,
                                           size_t error_capacity) {
    char *input;
    size_t allocation_size;
    if (fb_embedded_crawler_json_length > FB_CRAWLER_MAX_DATABASE_BYTES ||
        !fb_size_add(fb_embedded_crawler_json_length, YYJSON_PADDING_SIZE,
                     &allocation_size)) {
        fb_set_error(error, error_capacity,
                     "embedded crawler database size is invalid");
        return NULL;
    }
    input = malloc(allocation_size);
    if (input == NULL) {
        fb_set_error(error, error_capacity,
                     "cannot allocate embedded crawler database");
        return NULL;
    }
    memcpy(input, fb_embedded_crawler_json,
           fb_embedded_crawler_json_length);
    memset(input + fb_embedded_crawler_json_length, 0,
           YYJSON_PADDING_SIZE);
    return fb_crawler_db_parse_owned(
        input, fb_embedded_crawler_json_length, error, error_capacity);
}

void fb_crawler_db_free(fb_crawler_db *database) {
    size_t index;
    if (database == NULL) {
        return;
    }
    for (index = 0; index < database->chunk_count; ++index) {
        pcre2_code_free(database->chunks[index].code);
    }
    pcre2_code_free(database->combined.code);
    free(database->chunks);
    free(database);
}

static fb_crawler_tls *fb_crawler_tls_prepare(bool need_jit_stack) {
    fb_crawler_tls *tls = fb_crawler_tls_get();
    if (tls == NULL) {
        return NULL;
    }
    if (tls->match_data == NULL) {
        tls->match_data = pcre2_match_data_create(1, NULL);
    }
    if (tls->match_context == NULL) {
        tls->match_context = pcre2_match_context_create(NULL);
        if (tls->match_context != NULL &&
            (pcre2_set_match_limit(tls->match_context,
                                   FB_CRAWLER_MATCH_LIMIT) != 0 ||
             pcre2_set_depth_limit(tls->match_context,
                                   FB_CRAWLER_DEPTH_LIMIT) != 0 ||
             pcre2_set_heap_limit(tls->match_context,
                                  FB_CRAWLER_HEAP_LIMIT_KIB) != 0)) {
            pcre2_match_context_free(tls->match_context);
            tls->match_context = NULL;
        }
    }
    if (need_jit_stack && tls->jit_stack == NULL) {
        tls->jit_stack = pcre2_jit_stack_create(
            FB_CRAWLER_JIT_STACK_START_BYTES,
            FB_CRAWLER_JIT_STACK_MAX_BYTES, NULL);
    }
    if (need_jit_stack && tls->match_context != NULL &&
        tls->jit_stack != NULL && !tls->jit_stack_assigned) {
        pcre2_jit_stack_assign(tls->match_context, NULL, tls->jit_stack);
        tls->jit_stack_assigned = true;
    }
    return tls->match_data != NULL && tls->match_context != NULL &&
                   (!need_jit_stack || tls->jit_stack != NULL)
               ? tls
               : NULL;
}

static const char *fb_crawler_lower_subject(fb_crawler_tls *tls,
                                            const char *subject,
                                            size_t length) {
    size_t required;
    char *destination;
    char *resized;
    if (!fb_size_add(length, 1u, &required)) {
        return NULL;
    }
    if (required <= sizeof(tls->inline_subject)) {
        destination = tls->inline_subject;
    } else {
        if (required > tls->large_subject_capacity) {
            size_t capacity = tls->large_subject_capacity == 0u
                                  ? sizeof(tls->inline_subject) * 2u
                                  : tls->large_subject_capacity;
            while (capacity < required) {
                if (capacity > SIZE_MAX / 2u) {
                    capacity = required;
                    break;
                }
                capacity *= 2u;
            }
            resized = realloc(tls->large_subject, capacity);
            if (resized == NULL) {
                return NULL;
            }
            tls->large_subject = resized;
            tls->large_subject_capacity = capacity;
        }
        destination = tls->large_subject;
    }
    for (size_t index = 0; index < length; ++index) {
        destination[index] =
            (char)fb_ascii_lower((unsigned char)subject[index]);
    }
    destination[length] = '\0';
    return destination;
}

static int fb_crawler_match_chunk(const fb_crawler_chunk *chunk,
                                  fb_crawler_tls *tls,
                                  const char *subject,
                                  size_t length) {
    int result;
    if (chunk == NULL || chunk->code == NULL) {
        return PCRE2_ERROR_BADOPTION;
    }
    if (!chunk->jit_available) {
        return pcre2_match(chunk->code,
                           (PCRE2_SPTR)subject,
                           (PCRE2_SIZE)length,
                           0, 0, tls->match_data,
                           tls->match_context);
    }
    result = pcre2_jit_match(chunk->code,
                             (PCRE2_SPTR)subject,
                             (PCRE2_SIZE)length,
                             0, 0, tls->match_data,
                             tls->match_context);
    if (result < 0 && result != PCRE2_ERROR_NOMATCH) {
        /* A JIT stack/resource failure is not a match. Give the bounded
         * interpreter one chance to classify the same pattern correctly. */
        result = pcre2_match(chunk->code,
                             (PCRE2_SPTR)subject,
                             (PCRE2_SIZE)length,
                             0, 0, tls->match_data,
                             tls->match_context);
    }
    return result;
}

bool fb_crawler_is_bot(const fb_crawler_db *database,
                       const char *user_agent,
                       size_t user_agent_length) {
    fb_crawler_tls *tls;
    size_t index;
    if (database == NULL || user_agent == NULL || user_agent_length == 0) {
        return false;
    }
    if (fb_common_unfurler(user_agent, user_agent_length)) {
        return true;
    }
    tls = fb_crawler_tls_prepare(database->combined.jit_available ||
                                 database->jit_chunk_count != 0u);
    if (tls == NULL) {
        return false;
    }
    user_agent = fb_crawler_lower_subject(tls, user_agent, user_agent_length);
    if (user_agent == NULL) {
        return false;
    }
    if (database->combined.jit_available) {
        const int result = fb_crawler_match_chunk(
            &database->combined, tls, user_agent, user_agent_length);
        if (result >= 0) {
            return true;
        }
        if (result == PCRE2_ERROR_NOMATCH) {
            return false;
        }
        /* If the large optional combined pattern exhausted a bound, retain
         * correctness by trying the independently bounded small chunks. */
    }
    for (index = 0; index < database->chunk_count; ++index) {
        const fb_crawler_chunk *chunk = &database->chunks[index];
        const int result = fb_crawler_match_chunk(
            chunk, tls, user_agent, user_agent_length);
        if (result >= 0) {
            return true;
        }
    }
    return false;
}

fb_crawler_stats fb_crawler_db_stats(const fb_crawler_db *database) {
    fb_crawler_stats result = {0};
    if (database != NULL) {
        result.pattern_count = database->pattern_count;
        result.chunk_count = database->chunk_count;
        result.jit_chunk_count = database->jit_chunk_count;
        result.combined_jit = database->combined.jit_available;
    }
    return result;
}

