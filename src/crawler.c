static bool fb_common_unfurler(const char *user_agent, size_t length) {
    unsigned char state = 0;
    size_t index;
    for (index = 0; index < length; ++index) {
        const unsigned char character = (unsigned char)user_agent[index];
        unsigned char letter;
        unsigned char transition;
        if (state == 0) {
            state = fb_common_unfurler_root[character];
            continue;
        }
        letter = fb_common_unfurler_letter[character];
        if (letter == 0) {
            state = 0;
            continue;
        }
        transition = fb_common_unfurler_dfa[state][letter - 1u];
        if ((transition & FB_COMMON_UNFURLER_MATCH) != 0) {
            return true;
        }
        state = transition;
    }
    return false;
}

