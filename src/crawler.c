static char *fb_read_file(const char *path, size_t *length,
                          char *error, size_t error_capacity) {
    FILE *stream;
    long measured;
    size_t size;
    char *bytes;
    if (path == NULL || length == NULL) {
        fb_set_error(error, error_capacity, "crawler database path is missing");
        return NULL;
    }
    stream = fopen(path, "rb");
    if (stream == NULL) {
        fb_set_error(error, error_capacity, "cannot open crawler database: %s", path);
        return NULL;
    }
    if (fseek(stream, 0, SEEK_END) != 0 || (measured = ftell(stream)) < 0 ||
        fseek(stream, 0, SEEK_SET) != 0) {
        fb_set_error(error, error_capacity, "cannot size crawler database: %s", path);
        (void)fclose(stream);
        return NULL;
    }
    if ((unsigned long)measured > FB_CRAWLER_MAX_DATABASE_BYTES) {
        fb_set_error(error, error_capacity, "crawler database is unreasonably large");
        (void)fclose(stream);
        return NULL;
    }
    size = (size_t)measured;
    bytes = malloc(size + YYJSON_PADDING_SIZE);
    if (bytes == NULL) {
        fb_set_error(error, error_capacity, "cannot allocate crawler database");
        (void)fclose(stream);
        return NULL;
    }
    {
        const size_t bytes_read = fread(bytes, 1, size, stream);
        const int close_status = fclose(stream);
        if (bytes_read != size || close_status != 0) {
        fb_set_error(error, error_capacity, "cannot read crawler database: %s", path);
        free(bytes);
        return NULL;
        }
    }
    memset(bytes + size, 0, YYJSON_PADDING_SIZE);
    *length = size;
    return bytes;
}
